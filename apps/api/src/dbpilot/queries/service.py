def first_page(outcome: Outcome, page_size: int) -> RowsPage | None:
    run = outcome.run
    if run.status != "succeeded":
        return None
    return RowsPage(
        query_id=run.id,
        columns=[ResultColumn.model_validate(c) for c in run.columns or []],
        rows=outcome.rows[:page_size],
        offset=0,
        limit=page_size,
        total=len(outcome.rows),
    )


async def _stored_rows(container: Container, run: QueryRun) -> list[list[Any]]:
    if run.status != "succeeded":
        return []
    raw = await kv.cache_get(container.kv, f"result:{run.id}", RESULT_CACHE)
    if raw is None:
        raise GoneError(
            "This result is no longer kept (results are held for a limited time). Run the "
            "query again",
            code="result_expired",
        )
    rows: list[list[Any]] = orjson.loads(raw)["rows"]
    return rows


async def page(container: Container, run: QueryRun, offset: int, limit: int) -> RowsPage:
    rows = await _stored_rows(container, run)
    return RowsPage(
        query_id=run.id,
        columns=[ResultColumn.model_validate(c) for c in run.columns or []],
        rows=rows[offset : offset + limit],
        offset=offset,
        limit=limit,
        total=len(rows),
    )


def _cell(v: Any) -> Any:
    # Spreadsheet formula injection: a text cell starting with = + - @ is prefixed.
    if isinstance(v, str) and v[:1] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + v
    if isinstance(v, list | dict):
        return orjson.dumps(v).decode()
    return v


async def export(container: Container, run: QueryRun, fmt: str) -> AsyncIterator[bytes]:
    rows = await _stored_rows(container, run)
    names = [str(c.get("name", "")) for c in run.columns or []]
    if fmt == "json":
        yield orjson.dumps([dict(zip(names, r, strict=False)) for r in rows])
        return
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(names)
    yield buf.getvalue().encode()
    for start in range(0, len(rows), 1000):
        buf.seek(0)
        buf.truncate()
        for r in rows[start : start + 1000]:
            writer.writerow([_cell(v) for v in r])
        yield buf.getvalue().encode()


async def get_run(session: AsyncSession, p: Principal, run_id: uuid.UUID) -> QueryRun:
    ids = await visible_ids(session, p)
    run = await session.scalar(
        select(QueryRun).where(
            QueryRun.id == run_id,
            QueryRun.project_id == p.project_id,
            visible_clause(QueryRun.connection_id, ids),
        )
    )
    if run is None:
        raise NotFoundError("Query not found")
    return run


async def list_runs(
    session: AsyncSession,
    p: Principal,
    *,
    connection_id: uuid.UUID | None,
    status: str | None,
    source: str | None,
    mine: bool,
    cursor: str | None,
    limit: int,
) -> tuple[list[QueryRun], str | None]:
    """Newest first, keyset-paginated on (created_at, id), visible connections only."""
    ids = await visible_ids(session, p)
    stmt = select(QueryRun).where(
        QueryRun.project_id == p.project_id, visible_clause(QueryRun.connection_id, ids)
    )
    if connection_id:
        stmt = stmt.where(QueryRun.connection_id == connection_id)
    if status:
        stmt = stmt.where(QueryRun.status == status)
    if source:
        stmt = stmt.where(QueryRun.source == source)
    if mine:
        stmt = stmt.where(QueryRun.actor_id == p.user_id)
    after = decode_cursor(cursor)
    if after:
        at, _, last = after.partition("|")
        try:
            at_dt, last_id = datetime.fromisoformat(at), uuid.UUID(last)
            stmt = stmt.where(
                (QueryRun.created_at < at_dt)
                | ((QueryRun.created_at == at_dt) & (QueryRun.id < last_id))
            )
        except ValueError:
            pass  # a malformed cursor starts from the top
    rows = list(
        (
            await session.scalars(
                stmt.order_by(QueryRun.created_at.desc(), QueryRun.id.desc()).limit(limit + 1)
            )
        ).all()
    )
    nxt = None
    if len(rows) > limit:
        last_run = rows[limit - 1]
        nxt = encode_cursor(f"{last_run.created_at.isoformat()}|{last_run.id}")
    return rows[:limit], nxt


# ─── Previews ────────────────────────────────────────────────────────────────


def preview_sql(dialect: str, schema_name: str | None, name: str, limit: int) -> str:
    """``SELECT * FROM <object>`` with every identifier quoted by sqlglot for the dialect."""
    table = exp.table_(name, db=schema_name, quoted=True)
    query = exp.select("*").from_(table).limit(limit)
    return str(query.sql(dialect=guard.SQLGLOT_DIALECT[dialect]))


async def preview(
    container: Container,
    session: AsyncSession,
    p: Principal,
    access: ConnectionAccess,
    object_name: str,
    limit: int,
) -> Outcome:
    """The first rows of a table, view or collection (or the keys of a Redis key group),
    as a normal audited read. The object must be in the discovered schema, so the name is
    never free text in a statement."""
    from dbpilot.schema import service as schemas

    conn = access.connection
    snapshot = await schemas.ensure(container, session, conn, p.actor, org_id=p.org_id)
    obj = schemas.find_object(snapshot, object_name)
    if conn.kind in SQL_ENGINES:
        sql = preview_sql(conn.kind, obj.schema_name, obj.name, min(limit, conn.max_rows))
        return await run_sql(container, session, p, access, sql, source="preview")
    if conn.kind == "mongodb":
        body = MongoQueryIn(
            connection_id=conn.id, collection=obj.name, operation="find", limit=limit
        )
        return await run_mongo(container, session, p, access, body, source="preview")
    body_r = RedisQueryIn(
        connection_id=conn.id, command="SCAN", args=["0", "MATCH", obj.name, "COUNT", str(limit)]
    )
    return await run_redis(container, session, p, access, body_r, source="preview")
