SQL_ENGINES = ("postgresql", "mysql", "mssql", "sqlite")
RESULT_CACHE = "result"


@dataclass
class Outcome:
    run: QueryRun
    rows: list[list[Any]]


def new_run(
    conn: Connection,
    actor: Actor,
    *,
    source: str,
    statement: str,
    mode: str = "read",
    ai_generation_id: uuid.UUID | None = None,
    confirmation_id: uuid.UUID | None = None,
) -> QueryRun:
    return QueryRun(
        id=uuid.uuid4(),
        project_id=conn.project_id,
        connection_id=conn.id,
        engine=conn.kind,
        source=source,
        mode=mode,
        statement=statement,
        status="failed",
        row_count=0,
        truncated=False,
        duration_ms=0.0,
        columns=[],
        ai_generation_id=ai_generation_id,
        confirmation_id=confirmation_id,
        actor_id=actor.id,
        actor_label=actor.label,
        created_at=datetime.now(UTC),
    )


def to_out(run: QueryRun) -> QueryRunOut:
    return QueryRunOut(
        id=run.id,
        connection_id=run.connection_id,
        engine=run.engine,
        source=run.source,
        mode=run.mode,
        statement=run.statement,
        status=run.status,
        error=run.error,
        error_code=run.error_code,
        row_count=run.row_count,
        rows_affected=run.rows_affected,
        truncated=run.truncated,
        duration_ms=run.duration_ms,
        estimated_scan_rows=run.estimated_scan_rows,
        columns=[ResultColumn.model_validate(c) for c in run.columns or []],
        ai_generation_id=run.ai_generation_id,
        confirmation_id=run.confirmation_id,
        actor_id=run.actor_id,
        actor_label=run.actor_label,
        created_at=run.created_at,
    )


async def refuse(
    session: AsyncSession,
    p: Principal,
    conn: Connection,
    run: QueryRun,
    path: str,
    code: str,
    message: str,
) -> Outcome:
    """Record a refusal made before any database was contacted."""
    run.status, run.error, run.error_code = "refused", message, code
    session.add(run)
    record(
        session,
        p.actor,
        "query.refused",
        target_type="connection",
        target_id=conn.id,
        connection_id=conn.id,
        connection=conn.name,
        engine=conn.kind,
        statement=run.statement,
        source=run.source,
        code=code,
        reason=message,
        query_id=str(run.id),
        ai_generation_id=str(run.ai_generation_id) if run.ai_generation_id else None,
        **p.scope(),
    )
    await session.commit()
    metrics.GUARD_REFUSALS.labels(path, code).inc()
    metrics.QUERIES.labels(conn.kind, run.mode, run.source, "refused").inc()
    return Outcome(run, [])


def apply_error(run: QueryRun, conn: Connection, error: BaseException | None) -> None:
    if isinstance(error, ScanLimitError):
        run.status, run.error_code = "scan_limit", "scan_limit"
        run.estimated_scan_rows = error.estimated
        run.error = (
            f"The database expects this query to read about {error.estimated:,} rows, more "
            f"than this connection allows ({error.limit:,}). Narrow it with a filter, or raise "
            "the connection's scan limit"
        )
    elif isinstance(error, RedisCommandError) and error.code == "scan_limit":
        run.status, run.error_code, run.error = "scan_limit", "scan_limit", error.message
    elif isinstance(error, ScanUnknownError):
        run.status, run.error_code, run.error = "refused", "scan_unknown", str(error)
    elif isinstance(error, WriteStoppedError):
        run.status, run.error_code = "timeout", "timeout"
        run.error = (
            "The write ran past its time limit and was rolled back before it committed (on "
            "MySQL, schema changes that already ran stay applied)"
        )
    elif isinstance(error, QueryTimeoutError | TimeoutError) or (
        error is not None and is_timeout(error)
    ):
        run.status, run.error_code = "timeout", "timeout"
        run.error = (
            f"The database stopped the query after {conn.timeout_s} s, this connection's time "
            "limit. Narrow it, or raise the connection's timeout"
        )
    elif isinstance(error, TransactionTamperedError):
        run.status, run.error_code, run.error = "failed", "transaction_tampered", str(error)
    elif isinstance(error, AppError):
        run.status, run.error_code, run.error = "failed", error.code, error.message
    else:
        run.status, run.error_code = "failed", "database_error"
        run.error = friendly(gateway.error_text(error)) if error else "unknown error"


async def _execute(
    container: Container,
    session: AsyncSession,
    p: Principal,
    conn: Connection,
    run: QueryRun,
    work: Callable[[gateway.Handle], tuple[Any, int | None]],
    shape: Callable[[Any], tuple[list[dict[str, str]], list[list[Any]], bool, float]],
) -> Outcome:
    """Run ``work`` through the gateway; ``shape`` turns its result into the record."""
    rows: list[list[Any]] = []

    def on_done(
        result: tuple[Any, int | None] | None, error: BaseException | None
    ) -> dict[str, Any]:
        nonlocal rows
        if result is not None:
            value, estimated = result
            columns, rows, truncated, duration = shape(value)
            run.status, run.columns, run.truncated = "succeeded", columns, truncated
            run.row_count, run.duration_ms, run.estimated_scan_rows = len(rows), duration, estimated
        else:
            apply_error(run, conn, error)
        session.add(run)
        return {
            "query_id": str(run.id),
            "status": run.status,
            "row_count": run.row_count,
            "truncated": run.truncated,
            "estimated_scan_rows": run.estimated_scan_rows,
        }

    try:
        await gateway.read(
            container,
            session,
            conn,
            p.actor,
            action="query.run",
            work=work,
            org_id=p.org_id,
            on_done=on_done,
            details={
                "statement": run.statement,
                "source": run.source,
                "ai_generation_id": str(run.ai_generation_id) if run.ai_generation_id else None,
            },
        )
    except Exception:  # the outcome is on the run and in the audit entry
        if run.status == "failed" and not run.error:
            run.error = "The query could not be recorded"
    metrics.QUERIES.labels(conn.kind, "read", run.source, run.status).inc()
    if run.status == "succeeded":
        metrics.QUERY_SECONDS.labels(conn.kind, "read").observe(run.duration_ms / 1000)
        await kv.cache_set(
            container.kv,
            f"result:{run.id}",
            orjson.dumps({"columns": run.columns, "rows": rows}, default=str),
            container.settings.result_ttl_s,
            RESULT_CACHE,
        )
    return Outcome(run, rows)


def _sql_shape(value: SqlResult) -> tuple[list[dict[str, str]], list[list[Any]], bool, float]:
    return [asdict(c) for c in value.columns], value.rows, value.truncated, value.duration_ms


async def run_sql(
    container: Container,
    session: AsyncSession,
    p: Principal,
    access: ConnectionAccess,
    sql: str,
    *,
    source: str = "editor",
    ai_generation_id: uuid.UUID | None = None,
) -> Outcome:
    conn = access.connection
    if conn.kind not in SQL_ENGINES:
        raise UnprocessableError(
            f"This is a {conn.kind} connection: use its own query surface", code="engine_mismatch"
        )
    run = new_run(
        conn, p.actor, source=source, statement=sql.strip(), ai_generation_id=ai_generation_id
    )
    try:
        with metrics.GUARD_SECONDS.time():
            verdict = guard.check(sql, conn.kind)
    except guard.UnsafeSqlError as exc:
        return await refuse(
            session, p, conn, run, "ai" if source == "ai" else "editor", exc.code, exc.message
        )
    # MySQL and SQL Server run what the guard understood, re-serialized, not the text.
    executable = verdict.executable()

    def work(handle: gateway.Handle) -> tuple[SqlResult, int | None]:
        assert isinstance(handle, SaConnection)
        # No estimate, no run: the planner's error (or ScanUnknownError) is the outcome.
        estimated = estimate_scan(handle, executable, verdict.tables, verdict.aliases)
        if estimated > conn.max_scan_rows:
            raise ScanLimitError(estimated, conn.max_scan_rows)
        return run_query(handle, executable, conn.max_rows), estimated

    return await _execute(container, session, p, conn, run, work, _sql_shape)


def _doc_columns(rows: list[Any]) -> list[str]:
    names: dict[str, None] = {}
    for doc in rows[:200]:
        if isinstance(doc, dict):
            for key in doc:
                names.setdefault(str(key), None)
    return list(names)[:100]


def _mongo_shape(value: MongoResult) -> tuple[list[dict[str, str]], list[list[Any]], bool, float]:
    names = _doc_columns(value.rows)
    rows = [[doc.get(n) if isinstance(doc, dict) else doc for n in names] for doc in value.rows]
    return [{"name": n, "kind": "other"} for n in names], rows, value.truncated, value.duration_ms


async def run_mongo(
    container: Container,
    session: AsyncSession,
    p: Principal,
    access: ConnectionAccess,
    body: MongoQueryIn,
    *,
    source: str = "editor",
) -> Outcome:
    conn = access.connection
    if conn.kind != "mongodb":
        raise UnprocessableError("This is not a MongoDB connection", code="engine_mismatch")
    statement = json.dumps(
        body.model_dump(exclude={"connection_id", "page_size"}, exclude_none=True), default=str
    )
    run = new_run(conn, p.actor, source=source, statement=statement)
    try:
        req = check_request(
            MongoRequest(
                collection=body.collection,
                operation=body.operation,
                filter=parse_json_object(body.filter) or {},
                projection=parse_json_object(body.projection),
                sort=[(f, int(d)) for f, d in body.sort],
                skip=body.skip,
                limit=body.limit,
                pipeline=parse_json_object(body.pipeline) or [],
                field_name=body.field,
            )
        )
    except MongoRequestError as exc:
        return await refuse(session, p, conn, run, "mongodb", exc.code, exc.message)
    except ValueError as exc:  # Extended JSON that does not decode
        return await refuse(session, p, conn, run, "mongodb", "bad_json", str(exc)[:300])

    def work(handle: gateway.Handle) -> tuple[MongoResult, int | None]:
        assert isinstance(handle, MongoReader)
        estimated = handle.explain_scan(req)
        if estimated is not None and estimated > conn.max_scan_rows:
            raise ScanLimitError(estimated, conn.max_scan_rows)
        return handle.run(req, conn.max_rows), estimated

    return await _execute(container, session, p, conn, run, work, _mongo_shape)


def redis_rows(value: Any, max_rows: int) -> tuple[list[dict[str, str]], list[list[Any]], bool]:
    if isinstance(value, dict):
        items = [[k, v] for k, v in value.items()]
        return (
            [{"name": "field", "kind": "text"}, {"name": "value", "kind": "other"}],
            items[:max_rows],
            len(items) > max_rows,
        )
    if isinstance(value, list):
        items = [[i, v] for i, v in enumerate(value)]
        return (
            [{"name": "#", "kind": "number"}, {"name": "value", "kind": "other"}],
            items[:max_rows],
            len(items) > max_rows,
        )
    return [{"name": "value", "kind": "other"}], [[value]], False


async def run_redis(
    container: Container,
    session: AsyncSession,
    p: Principal,
    access: ConnectionAccess,
    body: RedisQueryIn,
    *,
    source: str = "editor",
) -> Outcome:
    conn = access.connection
    if conn.kind != "redis":
        raise UnprocessableError("This is not a Redis connection", code="engine_mismatch")
    statement = " ".join([body.command.upper(), *body.args])[:100_000]
    run = new_run(conn, p.actor, source=source, statement=statement)
    try:
        command, args = check_command(body.command, body.args)
    except RedisCommandError as exc:
        return await refuse(session, p, conn, run, "redis", exc.code, exc.message)

    def work(handle: gateway.Handle) -> tuple[RedisResult, int | None]:
        assert isinstance(handle, RedisReader)
        return handle.run(command, args, max_scan_keys=conn.max_scan_rows), None

    def shape(value: RedisResult) -> tuple[list[dict[str, str]], list[list[Any]], bool, float]:
        columns, rows, truncated = redis_rows(value.value, conn.max_rows)
        return columns, rows, truncated, value.duration_ms

    return await _execute(container, session, p, conn, run, work, shape)


