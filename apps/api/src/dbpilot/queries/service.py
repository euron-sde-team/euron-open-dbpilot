"""The read path: the only way a query reaches a connected database without a confirmed
write (those are ``queries/writes.py``). Every query, typed by a person, generated by the AI
assistant or built for a preview, goes through the same steps:

1. **The guard**: the SQL guard (exactly one read-only query), the MongoDB request check
   (read operations and stages only) or the Redis command allowlist. A refusal is recorded
   and audited, and no database is contacted.
2. **The gateway**: the connection opens read-only in the database itself (AC3), and the
   audit entry is written whatever happens (AC10).
3. **The scan limit**: the engine's own planner estimates what the query would read
   (``EXPLAIN``, MongoDB's query planner, ``DBSIZE`` for ``KEYS``), and anything above the
   connection's ``max_scan_rows`` is refused before it runs (AC2).
4. **The row limit**: at most ``max_rows`` rows are fetched; the result says ``truncated``.
5. **The record**: a ``query_runs`` row; the rows themselves go to the key-value store for
   ``RESULT_TTL_S`` so pages and exports never query the database again.
"""

